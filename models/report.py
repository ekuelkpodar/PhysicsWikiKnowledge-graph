"""Write models/REPORT.md and data/models/model_cards.json from the model outputs."""

from __future__ import annotations

import json
import sys

from models.common import ROOT, read_json, write_json

REPORT = ROOT / "models/REPORT.md"


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def main() -> int:
    g = read_json("genealogy_metrics.json")
    lp = read_json("link_predictions.json")
    sv = read_json("survival.json")
    mg = read_json("migration.json")
    ib = read_json("institutions_bump.json")
    fd = read_json("fields_alluvial.json")
    dq = read_json("data_quality.json")
    ask = None
    p = ROOT / "api/eval_results.json"
    if p.exists():
        ask = json.loads(p.read_text())

    gs = g["summary"]
    top = sorted(g["leaderboard"], key=lambda r: -r["yield_smoothed"])[:10]
    big = sorted(g["leaderboard"], key=lambda r: -r["descendants"])[:5]
    L = []
    L.append("# Model report\n")
    L.append(
        "Generated by `python -m models.report` from the JSON in `data/models/`. "
        "Every number below is produced by the code. None are hand-edited.\n"
    )

    L.append("## 1. Academic genealogy\n")
    L.append(
        f"- ADVISED DAG: **{gs['nodes']:,} people, {gs['edges']:,} edges**; "
        f"{gs['people_in_genealogy']:,} people have at least one advisor/student link "
        f"({gs['seed_in_genealogy']:,} of them in the 11,931-person seed)."
    )
    L.append(
        f"- {gs['weakly_connected_components']:,} separate family trees; the largest has "
        f"**{gs['largest_component']:,}** people. Deepest chain: **{gs['max_generation']}** generations."
    )
    L.append(
        f"- Base laureate rate among people who are someone's descendant: {pct(gs['base_laureate_rate_in_trees'], 2)}. "
        f"Yield is smoothed toward it with prior weight k={gs['smoothing_prior_k']}.\n"
    )
    L.append("| Founder | Descendants | Laureate descendants | Raw yield | Smoothed | Lift |")
    L.append("|---|---:|---:|---:|---:|---:|")
    for r in top:
        L.append(
            f"| {r['name']} | {r['descendants']:,} | {r['descendant_laureates']} | {pct(r['yield'])} | "
            f"{pct(r['yield_smoothed'])} | {r['lift']:.1f}× |"
        )
    L.append(
        "\nLargest trees: " + ", ".join(f"{r['name']} ({r['descendants']:,})" for r in big) + "\n"
    )

    L.append("## 2. Advisor-link prediction\n")
    L.append(
        f"Split: {lp['split']['train']:,} train / {lp['split']['test']:,} held-out ADVISED edges; "
        "2 negatives per positive (1 random, 1 hard negative sharing an institution).\n"
    )
    L.append(
        "| Model | AUC | AP | AUC (hard negs) | Hits@10 vs 100 random | Hits@10 vs plausible colleagues |"
    )
    L.append("|---|---:|---:|---:|---:|---:|")
    for k, m in lp["metrics"].items():
        L.append(
            f"| {k}{' **(best)**' if k == lp['best_model'] else ''} | {m['auc']:.3f} | {m['ap']:.3f} | "
            f"{m['auc_hard_negatives_only']:.3f} | {pct(m['hits@10_vs_100_random'])} | {pct(m['hits@10_vs_plausible'])} |"
        )
    L.append(
        f"\n- {lp['n_candidates']:,} candidate pairs scored for {lp['n_targets']:,} seed people with no advisor; top "
        f"{len(lp['predictions'])} exported with evidence."
    )
    ext = lp["p1066_external_check"]
    L.append(
        f"- **External check (P1066 'student of', never seen by the model):** for {ext['students_evaluable']} "
        f"advisor-less students whose recorded teacher is among their candidates "
        f"(~{ext['mean_candidates_per_student']:.0f} candidates each, chance ≈ {1 / ext['mean_candidates_per_student']:.0%}), "
        f"the teacher is ranked **#1 in {pct(ext['hit@1_rate'], 0)}** and top-3 in {pct(ext['hit@3_rate'], 0)}."
    )
    L.append(
        "- Feature coefficients (standardised LR): "
        + ", ".join(f"{k} {v:+.2f}" for k, v in lp["feature_coefficients"].items())
        + "\n"
    )

    L.append("## 3. Recognition (survival)\n")
    pop = sv["population"]
    L.append(
        f"- Population: {pop['n']:,} core physicists born {pop['cohorts'][0]}–{pop['cohorts'][1]}; "
        f"{pop['events']:,} first major awards; {pop['censored']:,} censored; "
        f"{pop['excluded_missing_death']} excluded (no death date, born before 1910). Clock: {pop['clock']}."
    )
    L.append(
        f"- Cox PH C-index: **{sv['cox']['c_index_test']:.3f}** held-out (train {sv['cox']['c_index_train']:.3f}). "
        f"Random survival forest: **{sv['rsf'].get('c_index_test', float('nan')):.3f}** held-out."
    )
    viol = sv["cox"]["ph_assumption_violations_p<0.01"]
    L.append(
        f"- Proportional-hazards violations (p<0.01): {', '.join(viol) if viol else 'none'}.\n"
    )
    L.append("| Covariate | HR | 95% CI | p |")
    L.append("|---|---:|---|---:|")
    for h in sorted(sv["cox"]["hazard_ratios"], key=lambda h: -h["hr"]):
        L.append(
            f"| {h['covariate']} | {h['hr']:.2f} | {h['lo']:.2f}–{h['hi']:.2f} | {h['p']:.2g} |"
        )
    L.append("")

    L.append("## 4. Migration\n")
    n = mg["notes"]
    L.append(
        f"- {n['n_moves']:,} person→employer moves for {n['n_people']:,} seed people; "
        f"{n['n_cross_border']:,} cross-border ({pct(n['n_cross_border'] / n['n_moves'])}). "
        f"Start year imputed for {pct(n['start_year_imputed_share'])}."
    )
    for w in mg["curated_windows"].values():
        L.append(
            f"- **{w['label']}**: {pct(w['share_abroad'])} took jobs abroad (n={w['n']}) vs "
            f"{pct(w['baseline_share_abroad'])} in {w['baseline_window'][0]}–{w['baseline_window'][1]} "
            f"(n={w['n_baseline']}). Top destinations: {', '.join(list(w['top_destinations'])[:3])}."
        )
    L.append(
        "- Automatically detected spikes: "
        + "; ".join(
            f"{s['origin']} {s['decade']}s ({pct(s['share_abroad'], 0)} vs {pct(s['baseline'], 0)})"
            for s in mg["shocks_detected"][:6]
        )
        + "\n"
    )

    L.append("## 5. Institutional centrality\n")
    leaders = {}
    for r in ib["rows"]:
        if r["rank"] == 1:
            leaders[r["decade"]] = r["label"]
    L.append(
        "Rank-1 institution by decade: "
        + ", ".join(f"{d}s {name}" for d, name in sorted(leaders.items()))
        + "\n"
    )

    L.append("## 6. Field evolution\n")
    L.append(
        f"- {fd['n_people_with_fields']:,} people list a specific field; {len(fd['alluvial']['nodes'])} cohort communities, "
        f"{len(fd['alluvial']['links'])} flows."
    )
    for c in fd["global_communities"]:
        L.append(f"  - [{c['id']}] {c['people']:,} people: {', '.join(c['top_fields'][:5])}")
    L.append("")

    L.append("## 7. Data-quality detector\n")
    s = dq["summary"]
    L.append(
        f"- {s['flagged_by_any_rule']:,} seed people hit at least one rule. Rule counts: "
        + ", ".join(f"{k} {v}" for k, v in s["rule_counts"].items() if v)
        + "."
    )
    L.append(
        "- Top 5: "
        + "; ".join(
            f"{it['name']} ({', '.join(it['reasons'][:2]) or 'outlier'})" for it in dq["items"][:5]
        )
        + "\n"
    )

    L.append("## 8. GraphRAG eval\n")
    if ask:
        L.append(
            f"- {ask['n']} questions, accuracy **{pct(ask['accuracy'])}** "
            f"(model `{ask['model']}`; exact-match of result sets against DuckDB ground truth)."
        )
    else:
        L.append("- Not run yet (`make api-eval` needs `ANTHROPIC_API_KEY`).")
    REPORT.write_text("\n".join(L) + "\n")

    best = lp["metrics"][lp["best_model"]]
    cards = [
        {
            "name": "Academic genealogy",
            "what": "Descendants, laureate yield, generation depth and ancestry PageRank on the advisor DAG.",
            "method": "NetworkX DAG; descendant sets by reverse topological union; PageRank on reversed edges; Bayesian-smoothed yield.",
            "metrics": f"{gs['edges']:,} edges, largest family {gs['largest_component']:,}, max depth {gs['max_generation']}.",
            "limits": "Advisor links exist for a minority of people and favour famous lineages; P185 imports from Mathematics Genealogy inflate some trees.",
        },
        {
            "name": "Advisor-link prediction",
            "what": "Suggests missing doctoral advisors.",
            "method": "Heterogeneous person/institution/award/field graph; node2vec (p=q=1) + logistic regression, compared to features-only LR and GraphSAGE.",
            "metrics": f"Best ({lp['best_model']}): AUC {best['auc']:.3f}, AP {best['ap']:.3f}, Hits@10 vs plausible colleagues {pct(best['hits@10_vs_plausible'])}; "
            f"P1066 teacher ranked #1 for {pct(lp['p1066_external_check']['hit@1_rate'], 0)} of {lp['p1066_external_check']['students_evaluable']} checkable students.",
            "limits": "Shared institution is the dominant signal, so colleagues can be mistaken for advisors. Treat predictions as leads.",
        },
        {
            "name": "Recognition survival model",
            "what": "Time from age 27 to first major award.",
            "method": "Cox PH (lifelines, L2 0.01) vs random survival forest (scikit-survival); correct right-censoring; missing deaths excluded.",
            "metrics": f"C-index Cox {sv['cox']['c_index_test']:.3f}, RSF {sv['rsf'].get('c_index_test', float('nan')):.3f} on a 25% hold-out.",
            "limits": "Associations only. Fame drives both recorded advisors and recorded awards; award list is curated.",
        },
        {
            "name": "Migration flows",
            "what": "Birth country → employer country by decade.",
            "method": "Employer spells with start dates (imputed birth+27 when missing); per-country emigration share vs own median to detect shocks.",
            "metrics": f"{n['n_moves']:,} moves, {pct(n['n_cross_border'] / n['n_moves'])} cross-border.",
            "limits": "Today's borders; imputed dates for many spells; only seed people.",
        },
        {
            "name": "Institutional centrality",
            "what": "Top 15 institutions per decade.",
            "method": "Decade-sliced person–institution bipartite graph projected to institutions; weighted eigenvector centrality.",
            "metrics": f"{len({r['institution'] for r in ib['rows']})} institutions ever in a top 15.",
            "limits": "Imputed spans; universities and their departments are separate Wikidata items.",
        },
        {
            "name": "Field evolution",
            "what": "Communities of co-occurring fields per 25-year birth cohort.",
            "method": "Field co-occurrence graph, Leiden (modularity), communities linked across cohorts by shared-field mass.",
            "metrics": f"{len(fd['alluvial']['nodes'])} cohort communities from {fd['n_people_with_fields']:,} people.",
            "limits": "Only a fraction of people list specific fields; generic 'physics' excluded.",
        },
        {
            "name": "Data-quality detector",
            "what": "Ranks likely Wikidata errors.",
            "method": "Weighted rules (impossible dates, advisor age gaps, fictional entries…) + isolation forest over record features.",
            "metrics": f"{s['flagged_by_any_rule']:,} people flagged by rules.",
            "limits": "Outlier ≠ error: famous people are statistically unusual too.",
        },
    ]
    write_json("model_cards.json", cards)
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
